  function money(value, settings) {
    const c = CURRENCIES[settings.currency] || CURRENCIES.BRL;
    try {
      return new Intl.NumberFormat(c.locale, { style: 'currency', currency: c.code }).format(value || 0);
    } catch (e) {
      return c.symbol + ' ' + (value || 0).toFixed(2);
    }
  }
  function curSymbol(settings) { return (CURRENCIES[settings.currency] || CURRENCIES.BRL).symbol; }

  function num(value, settings, dec) {
    const loc = (settings && settings.lang === 'pt') ? 'pt-BR' : (CURRENCIES[settings && settings.currency] || CURRENCIES.BRL).locale;
    const d = dec == null ? 2 : dec;
    try { return new Intl.NumberFormat(loc, { minimumFractionDigits: d, maximumFractionDigits: d }).format(value || 0); }
    catch (e) { return (value || 0).toFixed(d); }
  }

  return { STR, CURRENCIES, money, curSymbol, num,
    t: (lang, key) => (STR[lang] && STR[lang][key]) || STR.pt[key] || key };
